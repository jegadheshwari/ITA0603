import pandas as pd
from sklearn.linear_model import LinearRegression

data = {
    "Area": [800, 1000, 1200, 1400, 1600, 1800, 2000, 2200],
    "Bedrooms": [1, 2, 2, 3, 3, 3, 4, 4],
    "Age": [15, 12, 10, 8, 6, 5, 3, 2],
    "Price": [2000000, 2500000, 3000000, 3500000,
              4000000, 4500000, 5000000, 5500000]
}

df = pd.DataFrame(data)
X = df[["Area", "Bedrooms", "Age"]]
y = df["Price"]

model = LinearRegression()
model.fit(X, y)

house = pd.DataFrame([[1500, 3, 5]], columns=X.columns)
print("Predicted House Price: ₹", round(model.predict(house)[0], 2))
print("Training R2 Score:", round(model.score(X, y), 3))

