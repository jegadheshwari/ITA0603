# Credit Score Classification using Machine Learning

import pandas as pd
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import LabelEncoder
from sklearn.tree import DecisionTreeClassifier
from sklearn.metrics import accuracy_score, classification_report

# Create a sample dataset
data = {
    'Income': [25000, 40000, 60000, 80000, 30000, 90000, 50000, 70000, 20000, 100000],
    'Age': [22, 30, 35, 45, 25, 50, 32, 40, 21, 55],
    'Loan_Amount': [10000, 15000, 20000, 10000, 12000, 15000, 18000, 12000, 8000, 10000],
    'Payment_History': [2, 3, 4, 5, 2, 5, 3, 4, 1, 5],
    'Credit_Score': [
        'Poor', 'Average', 'Good', 'Good', 'Poor',
        'Good', 'Average', 'Good', 'Poor', 'Good'
    ]
}

df = pd.DataFrame(data)

# Separate input features and target
X = df.drop('Credit_Score', axis=1)
y = df['Credit_Score']

# Split the dataset
X_train, X_test, y_train, y_test = train_test_split(
    X, y, test_size=0.3, random_state=42
)

# Train the Decision Tree model
model = DecisionTreeClassifier(random_state=42)
model.fit(X_train, y_train)

# Predict credit scores
y_pred = model.predict(X_test)

# Evaluate the model
print("Credit Score Classification")
print("---------------------------")
print("Accuracy:", accuracy_score(y_test, y_pred))
print("\nClassification Report:")
print(classification_report(y_test, y_pred, zero_division=0))

# Predict credit score for a new customer
new_customer = pd.DataFrame([{
    'Income': 45000,
    'Age': 28,
    'Loan_Amount': 12000,
    'Payment_History': 3
}])

prediction = model.predict(new_customer)

print("New Customer Details:")
print(new_customer)
print("Predicted Credit Score:", prediction[0])