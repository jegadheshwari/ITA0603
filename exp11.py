import pandas as pd
from sklearn.tree import DecisionTreeClassifier
from sklearn.model_selection import train_test_split
from sklearn.metrics import accuracy_score

data = {
    "Income": [20000, 25000, 30000, 40000, 50000, 60000, 70000, 80000],
    "Debt": [15000, 18000, 20000, 10000, 12000, 15000, 10000, 8000],
    "Payment_History": [1, 0, 1, 1, 1, 1, 1, 1],
    "Credit_Score": ["Poor", "Poor", "Poor", "Average",
                     "Average", "Good", "Good", "Good"]
}

df = pd.DataFrame(data)
X = df[["Income", "Debt", "Payment_History"]]
y = df["Credit_Score"]

model = DecisionTreeClassifier(random_state=42)
model.fit(X, y)

prediction = model.predict([[55000, 12000, 1]])
print("Predicted Credit Score:", prediction[0])
print("Training Accuracy:", round(model.score(X, y) * 100, 2), "%")

