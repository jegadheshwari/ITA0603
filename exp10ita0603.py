import numpy as np
from sklearn.mixture import GaussianMixture
import matplotlib.pyplot as plt

# Create sample dataset
X = np.array([
    [1.0], [1.5], [2.0], [2.5], [3.0],
    [8.0], [8.5], [9.0], [9.5], [10.0]
])

# Create Gaussian Mixture Model
model = GaussianMixture(
    n_components=2,
    random_state=42,
    max_iter=100
)

# Train the model using EM algorithm
model.fit(X)

# Predict cluster labels
labels = model.predict(X)

# Display results
print("Data Points and Cluster Labels:")
for point, label in zip(X, labels):
    print(point[0], "-> Cluster", label)

print("\nCluster Means:")
print(model.means_)

print("\nNumber of Iterations:", model.n_iter_)
print("Converged:", model.converged_)

# Visualize clusters
plt.scatter(X[:, 0], np.zeros(len(X)),
            c=labels, cmap="viridis", s=100)
plt.xlabel("Data Points")
plt.title("EM Algorithm - Gaussian Mixture Model")
plt.yticks([])
plt.show()