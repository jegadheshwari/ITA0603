import pandas as pd
import math
from sklearn.tree import DecisionTreeClassifier, export_text
from sklearn.preprocessing import LabelEncoder

# Create dataset
data = {
    'Outlook': ['Sunny', 'Sunny', 'Overcast', 'Rain', 'Rain',
                'Rain', 'Overcast', 'Sunny', 'Sunny', 'Rain',
                'Sunny', 'Overcast', 'Overcast', 'Rain'],
    'Temperature': ['Hot', 'Hot', 'Hot', 'Mild', 'Cool',
                    'Cool', 'Cool', 'Mild', 'Cool', 'Mild',
                    'Mild', 'Mild', 'Hot', 'Mild'],
    'Humidity': ['High', 'High', 'High', 'High', 'Normal',
                 'Normal', 'Normal', 'High', 'Normal', 'Normal',
                 'Normal', 'High', 'Normal', 'High'],
    'Wind': ['Weak', 'Strong', 'Weak', 'Weak', 'Weak',
             'Strong', 'Strong', 'Weak', 'Weak', 'Weak',
             'Strong', 'Strong', 'Weak', 'Strong'],
    'Play': ['No', 'No', 'Yes', 'Yes', 'Yes',
             'No', 'Yes', 'No', 'Yes', 'Yes',
             'Yes', 'Yes', 'Yes', 'No']
}

df = pd.DataFrame(data)

# Encode categorical values
encoders = {}
encoded = pd.DataFrame()

for column in df.columns:
    encoders[column] = LabelEncoder()
    encoded[column] = encoders[column].fit_transform(df[column])

X = encoded.drop('Play', axis=1)
y = encoded['Play']

# Build decision tree
model = DecisionTreeClassifier(criterion='entropy', random_state=0)
model.fit(X, y)

# Display decision tree rules
print("Decision Tree:")
print(export_text(model, feature_names=list(X.columns)))

# Classify a new sample
new_sample = pd.DataFrame([{
    'Outlook': 'Overcast',
    'Temperature': 'Cool',
    'Humidity': 'High',
    'Wind': 'Weak'
}])

# Encode the new sample using existing encoders
new_encoded = new_sample.copy()

for column in new_sample.columns:
    new_encoded[column] = encoders[column].transform(new_sample[column])

prediction = model.predict(new_encoded)
result = encoders['Play'].inverse_transform(prediction)

print("\nNew Sample:", new_sample.to_dict(orient='records')[0])
print("Predicted Class:", result[0])